#!/usr/bin/env python3
"""Expand a campaign config into a deterministic Condor work list.

Every unit of work is one row: an ``integrate`` row builds the reusable
phase-space grid for a configuration, and the ``chunk`` rows generate events on
top of it.  Integration costs ~5.4 core-hours per configuration and generation
runs at ~9.75 s/event, so the split is what makes the campaign affordable.

This script only writes files.  Submission lives in ``submit_campaign.py``,
which enforces the approval gate.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

SUBMIT_TEMPLATE = """\
# Generated by make_cards.py for phase: {phase}
# Do not hand-edit; regenerate instead.
universe = vanilla
executable = {remote_root}/{bundle_dir}/lpc/run_transferred_canary.sh
initialdir = {remote_root}

should_transfer_files = YES
when_to_transfer_output = ON_EXIT
getenv = False
request_cpus = 1
request_memory = {memory}MB
request_disk = {disk}MB
+REQUIRED_OS = "rhel9"
requirements = (TARGET.OpSysAndVer == "AlmaLinux9")
notification = Never

arguments = {bundle_name} {bundle_sha} $(events) $(slice_index) $(ptlow) \
$(pthigh) $(shower) $(outname) $(gridname)
environment = "QCUT=$(qcut) CHUNK_INDEX=$(chunk) MODE={mode} KEEP_EVENTS=0"
transfer_input_files = {inputs}
transfer_output_files = {outputs}
{extra}
output = logs/{phase}.$(ClusterId).$(ProcId).out
error = logs/{phase}.$(ClusterId).$(ProcId).err
log = logs/{phase}.$(ClusterId).$(ProcId).log

queue events, slice_index, ptlow, pthigh, shower, qcut, chunk, outname, \
gridname from {joblist}
"""


def grid_name(shower: str, slice_index: int, qcut: float) -> str:
    return f"grid_{shower.lower()}_s{slice_index}_q{qcut:g}.tar.gz"


def run_name(shower: str, slice_index: int, qcut: float, chunk: int) -> str:
    return f"{shower.lower()}_s{slice_index}_q{qcut:g}_c{chunk}"


def qcut_scan_rows(cfg: dict) -> tuple[list[dict], list[dict]]:
    scan = cfg["qcut_scan"]
    slices = cfg["slices_GeV"]
    shower = cfg["baseline_shower"]
    per_chunk = scan["events_per_chunk"]
    n_chunks, remainder = divmod(scan["events_per_point"], per_chunk)
    if remainder:
        raise SystemExit(
            "events_per_point must be a whole number of chunks: "
            f"{scan['events_per_point']} / {per_chunk}"
        )

    integrate, chunks = [], []
    for qcut in scan["qcut_values_GeV"]:
        offset = scan["chunk_seed_offset_by_qcut"][str(qcut)]
        for slice_index in scan["slice_indices"]:
            ptlow, pthigh = slices[slice_index]
            grid = grid_name(shower, slice_index, qcut)
            integrate.append(
                {
                    # EVENTS=0 integrates and exits before the Rivet stage.
                    "events": 0,
                    "slice_index": slice_index,
                    "ptlow": ptlow,
                    "pthigh": pthigh,
                    "shower": shower,
                    "qcut": qcut,
                    "chunk": offset,
                    "outname": f"int_{run_name(shower, slice_index, qcut, offset)}.tar.gz",
                    # MODE=integrate treats this as the grid to PRODUCE, using
                    # exactly the name the chunk rows below will ask for.
                    "gridname": grid,
                }
            )
            for i in range(n_chunks):
                chunk = offset + i
                chunks.append(
                    {
                        "events": per_chunk,
                        "slice_index": slice_index,
                        "ptlow": ptlow,
                        "pthigh": pthigh,
                        "shower": shower,
                        "qcut": qcut,
                        "chunk": chunk,
                        "outname": f"{run_name(shower, slice_index, qcut, chunk)}.tar.gz",
                        "gridname": grid,
                        "seed": cfg["base_seed"] + 10_000 * slice_index + chunk,
                    }
                )
    return integrate, chunks


COLUMNS = (
    "events slice_index ptlow pthigh shower qcut chunk outname gridname"
).split()


def write_joblist(path: Path, rows: list[dict]) -> None:
    lines = [", ".join(str(row[c]) for c in COLUMNS) for row in rows]
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--campaign", type=Path, required=True)
    parser.add_argument("--phase", default="qcut_scan", choices=("qcut_scan",))
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--bundle-name", required=True)
    parser.add_argument("--bundle-sha", required=True)
    parser.add_argument("--bundle-dir", default="source_v7")
    parser.add_argument(
        "--remote-root",
        default="/uscms_data/d3/amandal2/sherpa3_pairsplit_canary_20260809_lpc1",
    )
    args = parser.parse_args()

    cfg = json.loads(args.campaign.read_text())
    integrate, chunks = qcut_scan_rows(cfg)

    out = args.output_dir
    out.mkdir(parents=True, exist_ok=True)
    write_joblist(out / "joblist_integrate.txt", integrate)
    write_joblist(out / "joblist_chunks.txt", chunks)

    bundle = f"{args.remote_root}/{args.bundle_dir}/{args.bundle_name}"
    common = dict(
        phase=args.phase,
        remote_root=args.remote_root,
        bundle_dir=args.bundle_dir,
        bundle_name=args.bundle_name,
        bundle_sha=args.bundle_sha,
    )
    (out / "integrate.sub").write_text(
        SUBMIT_TEMPLATE.format(
            mode="integrate",
            memory=2048,
            disk=3000,
            inputs=bundle,
            # The grid is the product of this phase; the run archive rides along.
            outputs="$(outname), $(gridname)",
            # Land the grid straight in grids/, where the chunk rows look for
            # it, instead of leaving a manual move between the two phases.
            extra=(
                'transfer_output_remaps = "$(gridname) = '
                f'{args.remote_root}/grids/$(gridname)"\n'
            ),
            joblist="joblist_integrate.txt",
            **common,
        )
    )
    (out / "chunks.sub").write_text(
        SUBMIT_TEMPLATE.format(
            mode="full",
            memory=2048,
            disk=4000,
            inputs=f"{bundle}, {args.remote_root}/grids/$(gridname)",
            outputs="$(outname)",
            extra="",
            joblist="joblist_chunks.txt",
            **common,
        )
    )

    rate = cfg["measured_rates"]
    core_hours = sum(r["events"] for r in chunks) * rate["seconds_per_event"] / 3600
    integration_hours = len(integrate) * rate["integration_core_hours_per_config"]
    summary = {
        "phase": args.phase,
        "integrate_jobs": len(integrate),
        "chunk_jobs": len(chunks),
        "total_events": sum(r["events"] for r in chunks),
        "estimated_generation_core_hours": round(core_hours, 1),
        "estimated_integration_core_hours": round(integration_hours, 1),
        "estimated_total_core_hours": round(core_hours + integration_hours, 1),
        "seeds_unique": len({r["seed"] for r in chunks}) == len(chunks),
    }
    if not summary["seeds_unique"]:
        raise SystemExit("FATAL: duplicate seeds in the generated work list")
    (out / "worklist_summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
